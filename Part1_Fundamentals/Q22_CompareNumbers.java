
package q22_comparenumbers;

public class Q22_CompareNumbers {

    public static void main(String[] args) {

        int a = 25;
        int b = 30;

        if (a > b) {
            System.out.println(a + " is greater than " + b);
        } else if (a < b) {
            System.out.println(a + " is less than " + b);
        } else {
            System.out.println(a + " is equal to " + b);
        }
    }
}
